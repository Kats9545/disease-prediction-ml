import streamlit as st
import pandas as pd
import joblib


# ==========================================
# PAGE CONFIGURATION
# ==========================================

st.set_page_config(
    page_title="Disease Prediction System",
    page_icon="🩺",
    layout="wide"
)


# ==========================================
# LOAD MODEL
# ==========================================

model = joblib.load("models/disease_model.pkl")
features = joblib.load("models/features.pkl")


# ==========================================
# TITLE
# ==========================================

st.title("🩺 Disease Prediction Using Machine Learning")

st.write(
    "Select the symptoms and the machine learning model "
    "will provide the most likely predictions."
)

st.warning(
    "⚠️ Educational project only. This system is not a "
    "medical diagnosis. Please consult a qualified "
    "healthcare professional."
)


# ==========================================
# SIDEBAR
# ==========================================

st.sidebar.header("About the System")

st.sidebar.write(
    "This application uses a Random Forest machine "
    "learning model trained on symptom data."
)

st.sidebar.write(
    "Select multiple symptoms for a more useful "
    "prediction."
)


# ==========================================
# SYMPTOM SELECTION
# ==========================================

st.subheader("🔍 Select Symptoms")

selected_symptoms = st.multiselect(
    "Choose the symptoms you are experiencing:",
    options=features
)


# ==========================================
# SHOW SELECTED SYMPTOMS
# ==========================================

if selected_symptoms:

    st.write("### Selected Symptoms")

    for symptom in selected_symptoms:
        st.write("✓", symptom)


# ==========================================
# PREDICTION BUTTON
# ==========================================

if st.button("🔮 Predict Disease"):

    if len(selected_symptoms) < 2:

        st.error(
            "Please select at least 2 symptoms "
            "before making a prediction."
        )

    else:

        # --------------------------------------
        # CREATE INPUT VECTOR
        # --------------------------------------

        input_data = pd.DataFrame(
            0,
            index=[0],
            columns=features
        )

        # Set selected symptoms to 1
        for symptom in selected_symptoms:
            input_data.loc[0, symptom] = 1


        # --------------------------------------
        # PREDICT
        # --------------------------------------

        prediction = model.predict(input_data)

        probabilities = model.predict_proba(input_data)[0]

        classes = model.classes_


        # --------------------------------------
        # GET TOP 3 PREDICTIONS
        # --------------------------------------

        probability_data = pd.DataFrame({
            "Disease": classes,
            "Probability": probabilities
        })

        probability_data = probability_data.sort_values(
            by="Probability",
            ascending=False
        )

        top_3 = probability_data.head(3)


        # --------------------------------------
        # MAIN RESULT
        # --------------------------------------

        st.subheader("🩺 Prediction Result")

        st.success(
            f"Most likely prediction: {top_3.iloc[0]['Disease']}"
        )


        # --------------------------------------
        # TOP 3 RESULTS
        # --------------------------------------

        st.subheader("📊 Top 3 Predictions")

        display_data = top_3.copy()

        display_data["Probability"] = (
            display_data["Probability"] * 100
        ).round(2)

        display_data = display_data.rename(
            columns={
                "Probability": "Probability (%)"
            }
        )

        st.dataframe(
            display_data,
            use_container_width=True,
            hide_index=True
        )


        # --------------------------------------
        # PROBABILITY CHART
        # --------------------------------------

        st.subheader("📈 Prediction Probability")

        chart_data = top_3.copy()

        chart_data = chart_data.set_index("Disease")

        chart_data["Probability"] = (
            chart_data["Probability"] * 100
        )

        st.bar_chart(
            chart_data["Probability"]
        )


        # --------------------------------------
        # MEDICAL DISCLAIMER
        # --------------------------------------

        st.info(
            "These results are generated by a machine "
            "learning model for educational purposes. "
            "They should not be considered a medical "
            "diagnosis or a substitute for professional "
            "medical advice."
        )